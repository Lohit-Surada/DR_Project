from pathlib import Path
from threading import RLock

import numpy as np
from PIL import Image
import torch
import torch.nn as nn
from torchvision import models, transforms


BACKEND_DIR = Path(__file__).resolve().parent.parent
MODEL_PATH = next(
    (
        path for path in (
            BACKEND_DIR / 'dr_classification' / 'efficientnet_b0_aptos_best.pth',
            BACKEND_DIR / 'efficientnet_b0_aptos_best.pth',
            BACKEND_DIR / 'model' / 'efficientnet_b0_aptos_best.pth',
        )
        if path.exists()
    ),
    BACKEND_DIR / 'dr_classification' / 'efficientnet_b0_aptos_best.pth',
)
ALLOWED_EXTENSIONS = {'jpg', 'jpeg', 'png', 'webp'}
CLASS_NAMES = [
    'No diabetic retinopathy',
    'Mild diabetic retinopathy',
    'Moderate diabetic retinopathy',
    'Severe diabetic retinopathy',
    'Proliferative diabetic retinopathy',
]
CLASS_SHORT_NAMES = ['No DR', 'Mild', 'Moderate', 'Severe', 'Proliferative DR']
CLASS_DESCRIPTIONS = [
    'No visible signs of diabetic retinopathy.',
    'Early changes that should be monitored regularly.',
    'Noticeable retinal changes that need clinical follow-up.',
    'Advanced changes requiring prompt specialist review.',
    'The most advanced stage; urgent specialist assessment is recommended.',
]
MODEL_LOCK = RLock()
MODEL = None
DEVICE = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

TRANSFORM = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[0.485, 0.456, 0.406],
        std=[0.229, 0.224, 0.225],
    ),
])


def get_model():
    global MODEL
    if MODEL is None:
        with MODEL_LOCK:
            if MODEL is None:
                if not MODEL_PATH.exists():
                    raise FileNotFoundError(
                        f'DR classification model not found. Restore efficientnet_b0_aptos_best.pth at {MODEL_PATH}.'
                    )
                model = models.efficientnet_b0(weights=None)
                model.classifier[1] = nn.Linear(1280, len(CLASS_NAMES))
                state_dict = torch.load(MODEL_PATH, map_location=DEVICE)
                model.load_state_dict(state_dict)
                model.to(DEVICE)
                model.eval()
                MODEL = model
    return MODEL


def classify_image(uploaded_file):
    with Image.open(uploaded_file) as image:
        rgb_image = image.convert('RGB')
        input_tensor = TRANSFORM(rgb_image).unsqueeze(0).to(DEVICE)

    model = get_model()
    with MODEL_LOCK, torch.no_grad():
        outputs = model(input_tensor)
        probabilities = torch.softmax(outputs, dim=1)[0].cpu().numpy()

    probabilities = np.asarray(probabilities, dtype=np.float64)
    total = probabilities.sum()
    if total <= 0 or len(probabilities) != len(CLASS_NAMES):
        raise ValueError('The model returned an invalid prediction.')
    probabilities /= total
    predicted_index = int(np.argmax(probabilities))

    scores = [
        {
            'name': CLASS_NAMES[index],
            'short_name': CLASS_SHORT_NAMES[index],
            'value': float(probabilities[index]),
            'percent': round(float(probabilities[index]) * 100, 1),
        }
        for index in range(len(CLASS_NAMES))
    ]

    genuine_confidence = round(float(probabilities[predicted_index]) * 100, 1)

    return {
        'title': CLASS_NAMES[predicted_index],
        'label': CLASS_SHORT_NAMES[predicted_index],
        'severity': CLASS_SHORT_NAMES[predicted_index],
        'description': CLASS_DESCRIPTIONS[predicted_index],
        'confidence': genuine_confidence,
        'genuine_confidence': genuine_confidence,
        'actual_confidence': genuine_confidence,
        'model_confidence': genuine_confidence,
        'is_illustrative': False,
        'illustrative_score': None,
        'confidence_type': 'actual',
        'scores': scores,
        'disclaimer': (
            'This result is generated by an AI model for research/educational purposes and '
            'should not be considered a medical diagnosis.'
        ),
    }